def serializar_json(obj):
    if isinstance(obj, np.integer):
        return int(obj)

    if isinstance(obj, np.floating):
        return float(obj)

    if pd.isna(obj):
        return None

    return str(obj)


def valor_limpo(valor):
    if pd.isna(valor):
        return None

    texto = str(valor).strip()

    if texto.lower() in [
        "",
        "nan",
        "none",
        "null",
        "#ne",
        "#nulo"
    ]:
        return None

    return texto


def escrever_json(nome, objeto):
    caminho = PASTA_DATA / nome

    with open(
        caminho,
        "w",
        encoding="utf-8"
    ) as arquivo:
        json.dump(
            objeto,
            arquivo,
            ensure_ascii=False,
            indent=2,
            default=serializar_json
        )

    return caminho


