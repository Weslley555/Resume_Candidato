def normalizar_texto(valor):
    """
    Normaliza texto para pesquisa:
    - remove acentos
    - converte para minúsculo
    - remove espaços duplicados
    """
    if pd.isna(valor):
        return ""

    valor = str(valor).strip().lower()

    valor = unicodedata.normalize("NFKD", valor)
    valor = "".join(
        c for c in valor
        if not unicodedata.combining(c)
    )

    valor = re.sub(r"\s+", " ", valor)

    return valor


def normalizar_colunas(df):
    df = df.copy()

    df.columns = [
        str(col).strip().upper()
        for col in df.columns
    ]

    return df


def normalizar_id(valor):
    """
    Normaliza SQ_CANDIDATO sem transformar em número.
    """
    if pd.isna(valor):
        return ""

    texto = str(valor).strip()

    if texto.lower() in ["nan", "none", "null", ""]:
        return ""

    return texto


def valor_monetario(valor):
    """
    Converte valores monetários do TSE para float.

    Exemplos:
    1234,56     -> 1234.56
    1.234,56    -> 1234.56
    1234.56     -> 1234.56
    """
    if pd.isna(valor):
        return 0.0

    texto = str(valor).strip()

    if texto.upper() in [
        "",
        "#NE",
        "#NULO",
        "NAN",
        "NONE",
        "NULL"
    ]:
        return 0.0

    texto = texto.replace("R$", "").replace(" ", "")

    try:
        if "," in texto:
            # Formato brasileiro: 1.234,56
            texto = texto.replace(".", "")
            texto = texto.replace(",", ".")
        else:
            # Caso tenha mais de um ponto, trata como separador de milhar
            if texto.count(".") > 1:
                texto = texto.replace(".", "")

        return float(texto)

    except Exception:
        return 0.0


def calcular_idade(data_nascimento, referencia=None):
    """
    Calcula idade a partir de DT_NASCIMENTO.
    """
    if pd.isna(data_nascimento):
        return None

    texto = str(data_nascimento).strip()

    if not texto or texto.upper() in ["#NE", "#NULO", "NAN", "NONE"]:
        return None

    formatos = [
        "%d/%m/%Y",
        "%Y-%m-%d",
        "%d-%m-%Y"
    ]

    data = None

    for formato in formatos:
        try:
            data = pd.to_datetime(
                texto,
                format=formato,
                errors="raise"
            )
            break
        except Exception:
            continue

    if data is None:
        try:
            data = pd.to_datetime(
                texto,
                dayfirst=True,
                errors="coerce"
            )
        except Exception:
            return None

    if pd.isna(data):
        return None

    if referencia is None:
        referencia = pd.Timestamp.today()

    idade = referencia.year - data.year

    if (
        (referencia.month, referencia.day)
        < (data.month, data.day)
    ):
        idade -= 1

    return idade


