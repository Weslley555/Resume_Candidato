def pesquisar_candidatos_avancada(
    nome,
    uf=None,
    cargo=None
):
    resultado = candidatos.copy()

    # Nome
    termo = (
        normalizar_texto(nome)
        if nome
        else ""
    )

    if termo:
        resultado = resultado[
            resultado["_NOME_BUSCA"]
            .str.contains(
                termo,
                regex=False,
                na=False
            )
        ]

    # UF
    if uf:
        resultado = resultado[
            resultado["_UF"] == uf.upper()
        ]

    # Cargo
    if cargo:
        if "DS_CARGO" in resultado.columns:
            resultado = resultado[
                resultado["DS_CARGO"]
                .fillna("")
                .astype(str)
                .str.upper()
                == cargo.upper()
            ]

    resultado = resultado.drop_duplicates(
        subset=["_CHAVE_CANDIDATO"]
    )

    return resultado


