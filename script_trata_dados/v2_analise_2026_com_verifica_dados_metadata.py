def vd_limpar(valor):
    """Normaliza somente para comparação, sem alterar os dados originais."""
    if valor is None:
        return None

    try:
        if pd.isna(valor):
            return None
    except Exception:
        pass

    texto = str(valor).strip()

    if texto.lower() in [
        "", "nan", "none", "null", "#ne", "#nulo"
    ]:
        return None

    return texto


def vd_normalizar_comparacao(valor):
    """Normaliza espaços e representações vazias para comparação."""
    valor = vd_limpar(valor)
    if valor is None:
        return None
    return " ".join(valor.split())


def vd_bool_reeleicao(valor):
    valor = vd_limpar(valor)
    if valor is None:
        return None

    texto = valor.upper()

    if texto in ["S", "SIM", "1", "TRUE"]:
        return True
    if texto in ["N", "NAO", "NÃO", "0", "FALSE"]:
        return False

    return valor


def vd_situacao_prestacao(valor):
    valor = vd_limpar(valor)
    if valor is None:
        return None

    texto = valor.upper()

    if texto in ["S", "SIM", "1", "TRUE"]:
        return "Sim"
    if texto in ["N", "NAO", "NÃO", "0", "FALSE"]:
        return "Não"

    return valor


def vd_idade(data_nascimento, referencia=None):
    """Mesma lógica de cálculo de idade usada no notebook."""
    if pd.isna(data_nascimento):
        return None

    texto = str(data_nascimento).strip()

    if not texto or texto.upper() in ["#NE", "#NULO", "NAN", "NONE"]:
        return None

    data = None

    for formato in ["%d/%m/%Y", "%Y-%m-%d", "%d-%m-%Y"]:
        try:
            data = pd.to_datetime(texto, format=formato)
            break
        except Exception:
            pass

    if data is None:
        try:
            data = pd.to_datetime(texto, errors="coerce")
        except Exception:
            return None

    if pd.isna(data):
        return None

    if referencia is None:
        referencia = pd.Timestamp.today()

    idade = referencia.year - data.year

    if (referencia.month, referencia.day) < (data.month, data.day):
        idade -= 1

    return idade


